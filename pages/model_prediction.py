from pathlib import Path
import pickle

import pandas as pd
import streamlit as st

st.title("🔮 Serialized Model Inference Portal")

BASE_DIR = Path(__file__).resolve().parents[1]
MODEL_PATH = BASE_DIR / "models" / "model.pkl"

@st.cache_resource
def load_serialized_machine_learning_model():
    with open(MODEL_PATH, "rb") as file:
        return pickle.load(file)

model = load_serialized_machine_learning_model()

st.subheader("🔬 Enter Operational Diagnostic Parameters")
with st.form("prediction_form"):
    user_age = st.slider("Select Target Subject Age", 18, 75, 35)
    user_income = st.slider("Select Target Subject Annual Income ($)", 20000, 200000, 65000, step=1000)
    user_credit_score = st.slider("Select Target Subject Credit Score", 300, 850, 680)
    user_loan_amount = st.slider("Select Target Subject Loan Amount ($)", 5000, 150000, 45000, step=1000)
    user_employment_years = st.slider("Select Target Subject Employment Years", 0.0, 35.0, 8.0, step=0.5)
    user_dti = st.slider("Select Target Subject Debt-to-Income Ratio", 0.05, 0.70, 0.30, step=0.01)
    submit_button = st.form_submit_button("Compute Prediction Probability")

if submit_button:
    input_data = pd.DataFrame([{
        "age": user_age,
        "annual_income": user_income,
        "credit_score": user_credit_score,
        "loan_amount": user_loan_amount,
        "employment_years": user_employment_years,
        "debt_to_income": user_dti,
    }])

    prediction = int(model.predict(input_data)[0])
    probability = float(model.predict_proba(input_data)[0, 1])

    st.markdown("---")
    st.subheader("🎯 Live Inference Computation Summary")
    c1, c2 = st.columns(2)
    with c1:
        st.metric(label="Predicted Default Risk Probability", value=f"{probability * 100:.2f}%")
    with c2:
        st.metric(label="Model Decision", value="Default Risk" if prediction == 1 else "Low Default Risk")

    if prediction == 1:
        st.warning(f"The trained model estimates a {probability * 100:.2f}% probability of default for these inputs.")
    else:
        st.success(f"The trained model estimates a {probability * 100:.2f}% probability of default for these inputs.")

    st.caption("Prediction generated by the serialized Logistic Regression pipeline loaded with st.cache_resource.")
